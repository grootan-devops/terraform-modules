def requested_controls(catalog):
    keys = set(FRAMEWORK_SHORT)
    return {c: v for c, v in catalog["controls"].items() if keys & set(v.get("standards", []))}


def codes(control):
    parts = []
    for key, short in FRAMEWORK_SHORT.items():
        if key in ("fsbp_v1_0_0", "tagging_v1_0_0", "ai_security_v1_0_0"):
            if key in control.get("standards", []):
                parts.append(short)
        elif key in control.get("requirements", {}):
            parts.append(f"{short} {', '.join(control['requirements'][key])}")
    return parts


def worst(statuses):
    present = [s for s in STATUS_ORDER if s in statuses]
    if len(present) > 1 and "NOT_APPLICABLE" in present:
        present.remove("NOT_APPLICABLE")
    return present[0] if present else "NOT_APPLICABLE"


def module_resource_types():
    found = defaultdict(set)
    for path in MODULES.rglob("*.tf"):
        if ".terraform" in path.parts or "tests" in path.parts:
            continue
        module = path.parent.relative_to(MODULES).as_posix()
        for tf_type in re.findall(r'^resource\s+"([a-z0-9_]+)"', path.read_text(), re.M):
            found[module].add(tf_type)
    return found


def map_rows(inventory, catalog):
    controls = requested_controls(catalog)
    by_module = defaultdict(list)
    for e in inventory["entries"]:
        by_module[e["module"].replace("modules/aws/", "")].append(e)
    rows = []
    for module, types in sorted(module_resource_types().items()):
        entries = by_module.get(module, [])
        for tf_type in sorted(types):
            per_control = defaultdict(list)
            for e in entries:
                if e["resource_type"] == tf_type:
                    for c in e["controls"]:
                        if c in controls:
                            per_control[c].append(e)
            aws_types = set(RESOURCE_TYPE_MAP.get(tf_type, []))
            for e in entries:
                for c in e["controls"]:
                    if c in controls and c not in per_control and aws_types & set(controls[c]["resource_types"]):
                        per_control[c].append(e)
            if not per_control:
                reason = NO_CONTROL_REASON.get(tf_type)
                if reason is None:
                    reason = ("No control in the selected standards evaluates this resource type; it configures the "
                              "service rather than holding data or exposing a network path."
                              if not any(aws_types & set(v["resource_types"]) for v in controls.values())
                              else "Applicable controls are not yet assessed for this module; see the gaps page.")
                rows.append(dict(module=module, resource=tf_type, control="", status="", title="", codes=[], note=reason))
                continue
            for c in sorted(per_control, key=lambda x: (x.split(".")[0], int(x.split(".")[1]))):
                es = per_control[c]
                status = worst({e["status"] for e in es})
                note = next((e["missing"] or e["remediation"] for e in es if e["status"] == status and (e["missing"] or e["remediation"])), "")
                rows.append(dict(module=module, resource=tf_type, control=c, status=status, title=controls[c]["title"],
                                 codes=codes(controls[c]), note=note if status not in ("PASS", "PROVIDER_MANAGED") else ""))
    return rows


def render_map(inventory, catalog):
    controls = requested_controls(catalog)
    cited = defaultdict(set)
    reasons = {}
    for e in inventory["entries"]:
        for c in e["controls"]:
            cited[c].add(e["status"])
            if e["missing"] or e["remediation"]:
                reasons.setdefault((c, e["status"]), (e["missing"] or e["remediation"]))
    managed = managed_aws_types()
    out = io.StringIO()
    w = out.write
    w("# Resource and compliance map\n\n")
    w("Generated by `scripts/compliance/render_compliance.py` from the [inventory](aws-compliance-inventory.json) and the "
      f"[Security Hub CSPM control catalog](data/securityhub-controls.json) (retrieved {catalog['retrieved']}). It answers "
      "two questions: which compliance codes each resource this library creates is held to, and which codes of the "
      "selected frameworks are not met in code, and why. The [CSV](resource-compliance-map.csv) carries the same rows.\n\n")
    w("Frameworks: AWS FSBP v1.0.0, CIS AWS Foundations v1.2.0, v1.4.0, v3.0.0 and v5.0.0, NIST SP 800-53 r5, "
      "NIST SP 800-171 r2, PCI DSS v3.2.1 and v4.0.1, AWS Resource Tagging, AI Security Best Practices and CRI Profile "
      "v2.2. Requirement codes come from AWS's mapping of each Security Hub control. FSBP, Tagging and AI Security have "
      "no codes of their own, so they show as membership. The AWS Control Tower service-managed standard is not "
      "applicable: the organization does not use Control Tower, and that standard can only be enabled from Control "
      "Tower.\n\n")
    w("Status: `PASS` met by default; `PARTIAL` met by default but overridable, opt-in, or met for part of the scope; "
      "`FAIL` not met; `REQUIRES_RUNTIME_VALIDATION` only a live account can show it; `NOT_SUPPORTED` the provider "
      "has no argument for it; `PROVIDER_MANAGED` AWS does it with no configuration; `NOT_APPLICABLE` the control "
      "does not apply to how the module uses the service. Where a control appears for several modules, the worst "
      "status counts. Meeting a control does not certify compliance with a framework.\n\n")

    w("## Summary by framework\n\n")
    w("| Framework | Controls | Evaluate resources this library creates | PASS | PARTIAL | FAIL | Runtime or not supported | "
      "Out of code (account level) | Not applicable (service not used) |\n"
      "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n")
    for key, short in FRAMEWORK_SHORT.items():
        ids = [c for c, v in controls.items() if key in v.get("standards", [])]
        tally = Counter()
        for c in ids:
            v = controls[c]
            if c in cited:
                s = worst(cited[c])
                tally[{"PROVIDER_MANAGED": "PASS"}.get(s, s)] += 1
            elif "AWS::::Account" in v["resource_types"]:
                tally["OUT"] += 1
            else:
                tally["NA"] += 1
        applies = sum(1 for c in ids if managed & set(controls[c]["resource_types"]))
        w(f"| {short} | {len(ids)} | {applies} | {tally['PASS']} | {tally['PARTIAL']} | {tally['FAIL']} | "
          f"{tally['REQUIRES_RUNTIME_VALIDATION'] + tally['NOT_SUPPORTED']} | {tally['OUT']} | "
          f"{tally['NA'] + tally['NOT_APPLICABLE']} |\n")
    w("\n")

    w("## Part 1: resources and the codes they are held to\n\n")
    w("Every resource type that a module under `modules/aws/` creates. A resource with no control has the reason in the "
      "last column.\n\n")
    rows = map_rows(inventory, catalog)
    current = None
    for r in rows:
        if r["module"] != current:
            if current is not None:
                w("\n")
            current = r["module"]
            w(f"### `{current}`\n\n| Resource | Control | Status | Compliance codes | Note |\n| --- | --- | --- | --- | --- |\n")
        w(f"| `{r['resource']}` | {r['control'] or '—'} | {('`' + r['status'] + '`') if r['status'] else '—'} | "
          f"{cell('; '.join(r['codes'])) or '—'} | {cell(r['note']) or '—'} |\n")
    w("\n")

    w("## Part 2: controls not met in code, and why\n\n")
    w("Every control of the selected frameworks that evaluates something this library could provide, and is not "
      "`PASS`. Opt-in organization policies count as `FAIL` until they are enabled and attached.\n\n")
    w("| Control | Title | Frameworks | Status | Reason |\n| --- | --- | --- | --- | --- |\n")
    for c in sorted(controls, key=lambda x: (x.split(".")[0], int(x.split(".")[1]))):
        v = controls[c]
        frameworks = ", ".join(FRAMEWORK_SHORT[k] for k in FRAMEWORK_SHORT if k in v.get("standards", []))
        if c in cited:
            s = worst(cited[c])
            if s in ("PASS", "PROVIDER_MANAGED", "NOT_APPLICABLE"):
                continue
            reason = reasons.get((c, s), "See the gaps page.")
        elif "AWS::::Account" in v["resource_types"]:
            s = "OUT_OF_CODE"
            reason = ACCOUNT_CONTROL_REASON.get(c.split(".")[0], "Account-level setting outside the modules.")
        else:
            continue
        w(f"| [{c}]({v['source']}) | {cell(v['title'])} | {frameworks} | `{s}` | {cell(reason)} |\n")
    w("\n")

    w("## Part 3: controls for services this library does not create\n\n")
    w("These controls evaluate AWS services that no module here creates, so they are not applicable to this library. "
      "They apply to any account that runs those services outside these modules.\n\n")
    w("| Service prefix | Controls | Frameworks touched | Resource types evaluated |\n| --- | ---: | --- | --- |\n")
    groups = defaultdict(list)
    for c, v in controls.items():
        if c not in cited and "AWS::::Account" not in v["resource_types"]:
            groups[c.split(".")[0]].append(c)
    for prefix in sorted(groups):
        ids = sorted(groups[prefix], key=lambda x: int(x.split(".")[1]))
        fw = sorted({FRAMEWORK_SHORT[k] for c in ids for k in controls[c].get("standards", []) if k in FRAMEWORK_SHORT},
                    key=list(FRAMEWORK_SHORT.values()).index)
        types = sorted({t for c in ids for t in controls[c]["resource_types"]})
        w(f"| {prefix} | {len(ids)} ({', '.join(ids)}) | {', '.join(fw)} | {cell(', '.join(types))} |\n")
    w("\n[Compliance documentation](README.md)\n")
    return out.getvalue()


def render_map_csv(inventory, catalog):
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(["module", "resource_type", "control", "status", "title", *FRAMEWORK_SHORT.values(), "note"])
    controls = requested_controls(catalog)
    for r in map_rows(inventory, catalog):
        v = controls.get(r["control"], {})
        cols = []
        for key in FRAMEWORK_SHORT:
            if key in ("fsbp_v1_0_0", "tagging_v1_0_0", "ai_security_v1_0_0"):
                cols.append("yes" if key in v.get("standards", []) else "")
            else:
                cols.append(" ".join(v.get("requirements", {}).get(key, [])))
        writer.writerow([r["module"], r["resource"], r["control"], r["status"], r["title"], *cols, r["note"]])
    return out.getvalue()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    inventory, catalog = load()
    outputs = {
        MATRIX: render_matrix(inventory, catalog),
        CSV_OUT: render_csv(inventory, catalog),
        STANDARDS_DOC: render_standards(inventory, catalog),
        GAPS_DOC: render_gaps(inventory, catalog),
        MAP_DOC: render_map(inventory, catalog),
        MAP_CSV: render_map_csv(inventory, catalog),
    }
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run scripts/compliance/render_compliance.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
    print(f"rendered {len(outputs)} files from {len(inventory['entries'])} inventory entries", file=sys.stderr)
    return 0


